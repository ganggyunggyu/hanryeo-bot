const run = () => {
  const raw = fs.readFileSync("scripts/qna-detail-list.json", "utf-8");
  const items: QnaDetail[] = JSON.parse(raw);

  let matched = 0;
  let unmatched = 0;

  const updated = items.map((item) => {
    if (item.hasComment) return item;

    const reply = CONTENT_REPLY_MAP[item.content];
    if (reply) {
      matched++;
      return { ...item, reply };
    }

    unmatched++;
    console.log(`[미매칭] #${item.no} "${item.title}"\n  본문: ${item.content}`);
    return item;
  });

  fs.writeFileSync("scripts/qna-detail-list.json", JSON.stringify(updated, null, 2), "utf-8");

  console.log(`\n=== 매칭 결과 ===`);
  console.log(`매칭 완료: ${matched}개`);
  console.log(`미매칭: ${unmatched}개`);
  console.log(`이미 답변: ${items.filter((i) => i.hasComment).length}개`);
};

run();
